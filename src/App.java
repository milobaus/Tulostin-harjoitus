public class App {
    public static void main(String[] args) throws Exception {
        
        String tekija = "Milo";


        // Muuttujat ja laskutoimitukset
        double luku1 = 5;
        double luku2 = 2;

        double tulo = luku1 * luku2;
        double summa = luku1 + luku2;
        double erotus = luku1 - luku2;
        double jako = luku1 / luku2;

        // Tulostukset
        System.out.println("Hei olen tulostin-ohjelma");
        System.out.println("Ohjelman tekijä: " + tekija);
        System.out.println("luku1-muuttujan arvo on " + luku1);
        System.out.println("luku2-muuttujan arvo on " + luku2);
        System.out.println("5 * 2 = " + tulo);
        System.out.println("5 + 2 = " + summa);
        System.out.println("5 - 2 = " + erotus);
        System.out.println("5 / 2 = " + jako);
    


    }
}
